<?php
/**
 * scripts/test_book_covers.php
 *
 * Автоматизированный тест-сьют для проверки строгого совпадения обложек книг:
 * - Различные форматы авторов: 'А. С. Пушкин', 'Пушкин А.С.', 'Александр Пушкин', 'Пушкин'
 * - Отбраковка несовпадающих авторов (Л. Н. Толстой, Толстой Л.Н., Александр Дюма, Лермонтов)
 * - Составные фамилии (Артур Конан Дойл, Конан Дойл А.)
 * - Соавторство (Ильф И.А. vs И. Ильф, Е. Петров)
 * - Совпадение и несовпадение заглавий книг (тома, части, несовпадающие заглавия)
 * - Работа в среде без расширения mbstring
 */

if (php_sapi_name() !== 'cli') {
    die("Тест запускается только из CLI.\n");
}

error_reporting(E_ALL & ~E_DEPRECATED);
ini_set('display_errors', '1');

require_once __DIR__ . '/../api/opac.php';

class BookCoversTestSuite
{
    private int $passed = 0;
    private int $failed = 0;

    private function assert(string $name, bool $condition, string $details = '')
    {
        if ($condition) {
            $this->passed++;
            echo "\033[32m[PASS]\033[0m {$name}\n";
            if ($details !== '') {
                echo "       \033[90m↳ {$details}\033[0m\n";
            }
        } else {
            $this->failed++;
            echo "\033[31m[FAIL]\033[0m {$name}\n";
            if ($details !== '') {
                echo "       \033[91m↳ {$details}\033[0m\n";
            }
        }
    }

    public function run(): bool
    {
        echo "\n=======================================================\n";
        echo "  QA ТЕСТ-СЬЮТ: СТРОГОЕ СОВПАДЕНИЕ ОБЛОЖЕК КНИГ (OPAC)\n";
        echo "  Проверка функции opac_is_strict_cover_match()\n";
        echo "=======================================================\n\n";

        $this->testAuthorEquivalenceFormats();
        $this->testAuthorMismatchRejection();
        $this->testCompoundNamesAndCoAuthors();
        $this->testTitleMatchingAndVolumes();
        $this->testTitleMismatchRejection();
        $this->testEmptyParametersHandling();
        $this->testLiveCoverResolverFallback();

        echo "\n=======================================================\n";
        echo "  ИТОГИ ТЕСТОВ ОБЛОЖЕК: {$this->passed} УСПЕШНО / {$this->failed} ОШИБОК\n";
        echo "=======================================================\n\n";

        return ($this->failed === 0);
    }

    /**
     * 1. Проверка различных легитимных форматов записи одного автора
     */
    private function testAuthorEquivalenceFormats()
    {
        echo "1. Эквивалентность форматов записи авторов:\n";

        $cases = [
            // Target, Found, Label
            ['А. С. Пушкин', 'А. С. Пушкин', 'Инициалы спереди: А. С. Пушкин <-> А. С. Пушкин'],
            ['А. С. Пушкин', 'Пушкин А.С.', 'Инициалы спереди <-> инициалы сзади без пробела: А. С. Пушкин <-> Пушкин А.С.'],
            ['Пушкин А.С.', 'А. С. Пушкин', 'Инициалы сзади <-> инициалы спереди: Пушкин А.С. <-> А. С. Пушкин'],
            ['Пушкин А.С.', 'Пушкин А. С.', 'Инициалы сзади с пробелом: Пушкин А.С. <-> Пушкин А. С.'],
            ['Пушкин А.С.', 'Пушкин А.С.', 'Идентичные каталожные формы: Пушкин А.С. <-> Пушкин А.С.'],
            ['А. С. Пушкин', 'Александр Пушкин', 'Инициалы <-> полное имя: А. С. Пушкин <-> Александр Пушкин'],
            ['Пушкин А.С.', 'Александр Пушкин', 'Каталог <-> полное имя: Пушкин А.С. <-> Александр Пушкин'],
            ['Александр Пушкин', 'Пушкин А.С.', 'Полное имя <-> каталог: Александр Пушкин <-> Пушкин А.С.'],
            ['Александр Сергеевич Пушкин', 'Пушкин А.С.', 'ФИО полностью <-> каталог: Александр Сергеевич Пушкин <-> Пушкин А.С.'],
            ['Пушкин Александр Сергеевич', 'А. С. Пушкин', 'Инвертированное ФИО <-> инициалы: Пушкин Александр Сергеевич <-> А. С. Пушкин'],
            ['Пушкин', 'Пушкин А.С.', 'Только фамилия <-> каталог: Пушкин <-> Пушкин А.С.'],
            ['Пушкин А.С.', 'Пушкин', 'Каталог <-> только фамилия: Пушкин А.С. <-> Пушкин'],
        ];

        foreach ($cases as $c) {
            $matched = opac_is_strict_cover_match('Капитанская дочка', $c[1], 'Капитанская дочка', $c[0]);
            $this->assert($c[2], $matched, "target='{$c[0]}' vs found='{$c[1]}'");
        }
    }

    /**
     * 2. Строгая отбраковка чужих авторов (защита от нерелевантных обложек)
     */
    private function testAuthorMismatchRejection()
    {
        echo "\n2. Защита от несовпадающих авторов (отбраковка чужих обложек):\n";

        $cases = [
            // Target, Found, Label
            ['А. С. Пушкин', 'Л. Н. Толстой', 'Пушкин (инициалы спереди) не должен совпасть с Толстым'],
            ['А. С. Пушкин', 'Толстой Л.Н.', 'Пушкин (инициалы спереди) не должен совпасть с Толстой Л.Н.'],
            ['Пушкин А.С.', 'Л. Н. Толстой', 'Пушкин (каталог) не должен совпасть с Толстым'],
            ['Пушкин А.С.', 'Толстой Л.Н.', 'Пушкин (каталог) не должен совпасть с Толстой Л.Н.'],
            ['Александр Пушкин', 'Александр Дюма', 'Одинаковые имена «Александр», но разные фамилии (Пушкин vs Дюма)'],
            ['Пушкин', 'Лермонтов', 'Разные фамилии из одного слова: Пушкин vs Лермонтов'],
            ['Чехов А.П.', 'Достоевский Ф.М.', 'Чехов vs Достоевский'],
            ['Гоголь Н.В.', 'Булгаков М.А.', 'Гоголь vs Булгаков'],
            ['А. С. Пушкин', '', 'Если в каталоге автор указан, а в найденной обложке пуст — отбраковка'],
        ];

        foreach ($cases as $c) {
            $matched = opac_is_strict_cover_match('Собрание сочинений', $c[1], 'Собрание сочинений', $c[0]);
            $this->assert($c[2], !$matched, "target='{$c[0]}' vs found='{$c[1]}' -> отклонено: " . (!$matched ? 'OK' : 'ОШИБКА'));
        }
    }

    /**
     * 3. Составные фамилии, псевдонимы и соавторство
     */
    private function testCompoundNamesAndCoAuthors()
    {
        echo "\n3. Составные имена и соавторы:\n";

        $cases = [
            ['Конан Дойл А.', 'Артур Конан Дойл', true, 'Конан Дойл А. <-> Артур Конан Дойл'],
            ['Мамин-Сибиряк Д.Н.', 'Дмитрий Мамин-Сибиряк', true, 'Мамин-Сибиряк Д.Н. <-> Дмитрий Мамин-Сибиряк'],
            ['Ильф И.А.', 'И. Ильф, Е. Петров', true, 'Ильф И.А. входит в коллектив авторов «И. Ильф, Е. Петров»'],
            ['Петров Е.П.', 'Илья Ильф, Евгений Петров', true, 'Петров Е.П. входит в коллектив авторов «Илья Ильф, Евгений Петров»'],
            ['Стругацкий А.Н.', 'Аркадий и Борис Стругацкие', true, 'Стругацкий А.Н. <-> Аркадий и Борис Стругацкие'],
        ];

        foreach ($cases as $c) {
            $matched = opac_is_strict_cover_match('Книга', $c[1], 'Книга', $c[0]);
            $this->assert($c[3], $matched === $c[2], "target='{$c[0]}' vs found='{$c[1]}'");
        }
    }

    /**
     * 4. Совпадение заглавий и обработка томов / частей
     */
    private function testTitleMatchingAndVolumes()
    {
        echo "\n4. Проверка заглавий (тома, части, кавычки, регистр):\n";

        $cases = [
            ['Капитанская дочка', 'Капитанская дочка', true, 'Точное совпадение заглавия'],
            ['«Капитанская дочка»', 'Капитанская дочка', true, 'Заглавие в кавычках и без кавычек'],
            ['Война и мир. Том 1', 'Война и мир', true, 'Отсечение суффикса «Том 1»'],
            ['Война и мир ч. 2', 'Война и мир', true, 'Отсечение суффикса «ч. 2»'],
            ['Евгений Онегин : роман в стихах', 'Евгений Онегин', true, 'Подзаголовок после двоеточия'],
        ];

        foreach ($cases as $c) {
            $matched = opac_is_strict_cover_match($c[1], 'Пушкин А.С.', $c[0], 'Пушкин А.С.');
            $this->assert($c[3], $matched === $c[2], "targetTitle='{$c[0]}' vs foundTitle='{$c[1]}'");
        }
    }

    /**
     * 5. Отбраковка несовпадающих заглавий
     */
    private function testTitleMismatchRejection()
    {
        echo "\n5. Отбраковка несовпадающих заглавий книг:\n";

        $cases = [
            ['Капитанская дочка', 'Евгений Онегин', 'Разные книги одного автора (Капитанская дочка vs Евгений Онегин)'],
            ['Мастер и Маргарита', 'Белая гвардия', 'Разные книги Булгакова (Мастер и Маргарита vs Белая гвардия)'],
            ['Руслан и Людмила', 'Сказка о царе Салтане', 'Разные сказки Пушкина'],
        ];

        foreach ($cases as $c) {
            $matched = opac_is_strict_cover_match($c[1], 'Пушкин А.С.', $c[0], 'Пушкин А.С.');
            $this->assert($c[2], !$matched, "targetTitle='{$c[0]}' vs foundTitle='{$c[1]}'");
        }
    }

    /**
     * 6. Граничные случаи: пустые строки, пробелы, спецсимволы
     */
    private function testEmptyParametersHandling()
    {
        echo "\n6. Граничные случаи и пустые значения:\n";

        $this->assert('Пустое целевое заглавие -> отказ', !opac_is_strict_cover_match('Книга', 'Автор', '', 'Автор'));
        $this->assert('Пустое найденное заглавие -> отказ', !opac_is_strict_cover_match('', 'Автор', 'Книга', 'Автор'));
        $this->assert('Оба заглавия пустые -> отказ', !opac_is_strict_cover_match('', '', '', ''));
    }

    /**
     * 7. Проверка функции разрешения обложки opac_resolve_book_cover
     */
    private function testLiveCoverResolverFallback()
    {
        echo "\n7. Интеграция с резолвером opac_resolve_book_cover():\n";

        $res = opac_resolve_book_cover('Капитанская дочка', 'Пушкин А.С.');
        $ok = (!empty($res['ok']) && !empty($res['url']) && strpos($res['url'], 'http') === 0);
        $this->assert(
            'Получение обложки для «Капитанская дочка» Пушкин А.С.',
            $ok,
            $ok ? "Источник: {$res['source']}, URL: {$res['url']}" : "Обложка не найдена"
        );
    }
}

$suite = new BookCoversTestSuite();
$success = $suite->run();
exit($success ? 0 : 1);
